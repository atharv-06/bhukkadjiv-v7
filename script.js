/*
    Keep your existing large MR object
    and PH object here.
*/


const orig =
    new WeakMap();


function applyLanguage() {

    const isMarathi =
        state.language;


    /*
        Translate regular text nodes.
    */

    const walker =
        document.createTreeWalker(
            document.body,
            NodeFilter.SHOW_TEXT,
            {
                acceptNode(node) {

                    const parent =
                        node.parentNode;


                    if (
                        parent &&
                        parent.closest(
                            "script,style"
                        )
                    ) {

                        return NodeFilter.FILTER_REJECT;
                    }


                    return NodeFilter.FILTER_ACCEPT;
                }
            }
        );


    const nodes = [];


    while (walker.nextNode()) {

        nodes.push(
            walker.currentNode
        );

    }


    nodes.forEach(node => {

        const originalText =
            node.nodeValue.trim();


        if (isMarathi) {

            if (
                typeof MR !== "undefined" &&
                MR[originalText]
            ) {

                if (
                    !orig.has(node)
                ) {

                    orig.set(
                        node,
                        node.nodeValue
                    );

                }


                node.nodeValue =
                    MR[originalText];

            }

        } else {

            if (orig.has(node)) {

                node.nodeValue =
                    orig.get(node);


                orig.delete(node);

            }

        }

    });


    /*
        data-mr elements.
    */

    qsa("[data-mr]").forEach(
        element => {

            if (!element.dataset.en) {

                element.dataset.en =
                    element.innerHTML;

            }


            element.innerHTML =
                isMarathi
                    ? element.dataset.mr
                    : element.dataset.en;

        }
    );


    /*
        Placeholders.
    */

    qsa("[placeholder]").forEach(
        element => {

            if (!element.dataset.ph) {

                element.dataset.ph =
                    element.placeholder;

            }


            if (
                isMarathi &&
                typeof PH !== "undefined" &&
                PH[element.dataset.ph]
            ) {

                element.placeholder =
                    PH[element.dataset.ph];

            } else {

                element.placeholder =
                    element.dataset.ph;

            }

        }
    );


    document.documentElement.lang =
        isMarathi
            ? "mr"
            : "en";


    const languageButton =
        $("lang");


    if (languageButton) {

        languageButton.textContent =
            isMarathi
                ? "EN"
                : "मराठी";

    }

}


function setupLanguage() {

    /*
        Store option values.
    */

    qsa("option").forEach(
        option => {

            option.value =
                option.textContent;

        }
    );


    const button =
        $("lang");


    if (!button) {
        return;
    }


    const saved =
        storage.get(
            "bj_mr",
            ""
        );


    if (saved) {

        state.language =
            true;

        applyLanguage();

    }


    button.addEventListener(
        "click",
        () => {

            state.language =
                !state.language;


            storage.set(
                "bj_mr",
                state.language
                    ? "1"
                    : ""
            );


            applyLanguage();

        }
    );

}


