const storage = {

    get(key, fallback = null) {

        try {

            const value =
                localStorage.getItem(key);

            return value ?? fallback;

        } catch (error) {

            console.warn(
                `Unable to read localStorage: ${key}`,
                error
            );

            return fallback;
        }
    },


    set(key, value) {

        try {

            localStorage.setItem(
                key,
                value
            );

            return true;

        } catch (error) {

            console.warn(
                `Unable to save localStorage: ${key}`,
                error
            );

            return false;
        }
    }

};


/* =========================================================
   NAVIGATION
========================================================= */

function getNavigationTarget(href) {

    if (!href || !href.startsWith("#")) {
        return null;
    }


    /* Collaboration */

    if (href === "#collab") {

        return (
            $("collab") ||
            $("enquire")
        );
    }


    /* Trail */

    if (href === "#trail") {

        const trail =
            $("trail");

        if (trail) {
            return trail;
        }


        const trailPosts =
            $("tposts");

        const trailFilters =
            $("tfilters");


        if (trailPosts) {

            return (
                trailPosts.closest("section") ||
                trailPosts
            );
        }


        if (trailFilters) {

            return (
                trailFilters.closest("section") ||
                trailFilters
            );
        }


        return null;
    }


    /* Normal section */

    try {

        return document.querySelector(href);

    } catch {

        return null;
    }
}


/* =========================================================
   SMOOTH SCROLL
========================================================= */

function smoothScrollTo(target) {

    if (!target) {
        return;
    }


    const nav =
        qs("nav");


    const navHeight =
        nav
            ? nav.getBoundingClientRect().height
            : 0;


    const offset = 15;


    const position =
        target.getBoundingClientRect().top +
        window.scrollY -
        navHeight -
        offset;


    window.scrollTo({

        top: Math.max(0, position),

        behavior: "smooth"

    });
}


/* =========================================================
   NAVIGATION EVENTS
========================================================= */

function setupNavigation() {

    qsa('a[href^="#"]').forEach(link => {

        link.addEventListener(
            "click",
            event => {

                const href =
                    link.getAttribute("href");


                if (
                    !href ||
                    href === "#"
                ) {
                    return;
                }


                const target =
                    getNavigationTarget(href);


                if (!target) {
                    return;
                }


                event.preventDefault();


                smoothScrollTo(target);


                /*
                    Update URL without triggering
                    browser's default jump.
                */

                try {

                    history.pushState(
                        null,
                        "",
                        href
                    );

                } catch {}


                closeMobileMenu();

            }
        );

    });

}


/* =========================================================
   INITIAL HASH
========================================================= */

function handleInitialHash() {

    const hash =
        window.location.hash;


    if (!hash) {
        return;
    }


    setTimeout(() => {

        const target =
            getNavigationTarget(hash);


        if (target) {
            smoothScrollTo(target);
        }

    }, 250);

}


