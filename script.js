function setupMobileMenu() {

    const nav =
        qs("nav");


    if (!nav) {
        return;
    }


    let menuButton =
        $("mobileMenu");


    /*
        Create mobile menu button
        automatically.
    */

    if (!menuButton) {

        menuButton =
            document.createElement("button");


        menuButton.id =
            "mobileMenu";


        menuButton.type =
            "button";


        menuButton.className =
            "mobile-menu-btn";


        menuButton.setAttribute(
            "aria-label",
            "Open navigation menu"
        );


        menuButton.setAttribute(
            "aria-expanded",
            "false"
        );


        menuButton.innerHTML =
            "☰";


        const tools =
            nav.querySelector(".tools");


        if (tools) {

            nav.insertBefore(
                menuButton,
                tools
            );

        } else {

            nav.appendChild(
                menuButton
            );
        }

    }


    menuButton.addEventListener(
        "click",
        event => {

            event.stopPropagation();

            const isOpen =
                nav.classList.toggle(
                    "mobile-open"
                );


            menuButton.innerHTML =
                isOpen
                    ? "✕"
                    : "☰";


            menuButton.setAttribute(
                "aria-expanded",
                String(isOpen)
            );

        }
    );


    document.addEventListener(
        "click",
        event => {

            if (
                !nav.contains(event.target)
            ) {

                closeMobileMenu();

            }

        }
    );

}


function closeMobileMenu() {

    const nav =
        qs("nav");


    const button =
        $("mobileMenu");


    if (!nav) {
        return;
    }


    nav.classList.remove(
        "mobile-open"
    );


    if (button) {

        button.innerHTML =
            "☰";


        button.setAttribute(
            "aria-expanded",
            "false"
        );

    }

}


